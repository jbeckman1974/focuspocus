#!/usr/bin/env bash
# Validate an existing candidate on a fresh disposable stack and dedicated test DB.
set -euo pipefail
: "${FOCUSPOCUS_IMAGE:?set FOCUSPOCUS_IMAGE to the local candidate image}"
: "${EXPECTED_ARCH:?set EXPECTED_ARCH to its native architecture}"
root=$(pwd -P)
test -f ops/db-init.sh
test ! -L build
mkdir -p build
scratch=$(mktemp -d "$root/build/qa-stack.XXXXXXXXXX")
slug=$(basename "$scratch" | tr '[:upper:].' '[:lower:]-')
export COMPOSE_PROJECT_NAME="focuspocus-$slug"
export FOCUSPOCUS_SECRET_DIR="$scratch/secrets" APP_ENV=development FOCUSPOCUS_PORT=0
export ALLOWED_HOSTS=127.0.0.1,localhost,web
compose=(docker compose -f compose.yaml -f ops/compose.tests.yaml --profile testing)
dc() { "${compose[@]}" "$@"; }
if [[ -n $(docker ps -aq --filter "label=com.docker.compose.project=$COMPOSE_PROJECT_NAME") ||
      -n $(docker volume ls -q --filter "label=com.docker.compose.project=$COMPOSE_PROJECT_NAME") ]]; then
  echo 'Generated test project name is already in use.' >&2
  exit 1
fi
cleanup() {
  code=$?
  if (( code != 0 )); then dc ps -a >&2 || true; fi
  # Only the unique test project and directory generated by this invocation are removed.
  if dc down -v --remove-orphans; then
    rm -rf -- "$scratch"
  else
    echo "Clean up disposable project $COMPOSE_PROJECT_NAME and its secret directory $scratch" >&2
    code=1
  fi
  exit "$code"
}
trap cleanup EXIT
python3 ops/init-secrets.py "$FOCUSPOCUS_SECRET_DIR"
bash ops/assert-native.sh
image_id=$(docker image inspect --format '{{.Id}}' "$FOCUSPOCUS_IMAGE")
test "$(docker image inspect --format '{{.Os}}/{{.Architecture}}' "$FOCUSPOCUS_IMAGE")" = "linux/$EXPECTED_ARCH"
docker run --rm "$image_id" python /srv/ops/check-runtime.py
dc up --wait --wait-timeout 120 -d db test-db
dc exec -T db sh /docker-entrypoint-initdb.d/10-roles.sh
dc run --rm --no-deps migrate
dc run --rm --no-deps migrate python manage.py migrate --check
dc run --rm --no-deps migrate
dc run --rm --no-deps test python manage.py makemigrations --check --dry-run
dc run --rm --no-deps test
dc up --wait --wait-timeout 120 -d web worker
dc exec -T worker python manage.py worker_health
for service in web worker; do
  test "$(docker inspect --format '{{.Image}}' "$(dc ps -q "$service")")" = "$image_id"
done

bash ops/qa-browser.sh
dc exec -T web python - < ops/check-worker.py
python3 -B ops/qa-replacement.py before "$scratch/probe-checkpoint"
before=$(dc exec -T web python - < ops/check-database.py)
web_id=$(dc ps -q web)
worker_id=$(dc ps -q worker)
dc up -d --no-deps --wait --wait-timeout 120 --force-recreate web worker
test "$(dc ps -q web)" != "$web_id"
test "$(dc ps -q worker)" != "$worker_id"
test "$(dc exec -T web python - < ops/check-database.py)" = "$before"
python3 -B ops/qa-replacement.py after "$scratch/probe-checkpoint"
dc exec -T worker python manage.py worker_health
dc exec -T web python - < ops/check-worker.py
saved=$(dc exec -T web python - < ops/check-database.py)

# The test-db volume is independent of the live fixture and has matching precreated roles.
dc exec -T db pg_dump -U postgres --format=custom focuspocus > "$scratch/fixture.dump"
dc exec -T test-db createdb -U postgres -O fpmigrate restored_fixture
dc exec -T test-db pg_restore -U fpmigrate --single-transaction --exit-on-error --no-owner --no-acl \
    -d restored_fixture < "$scratch/fixture.dump"
dc exec -T -e POSTGRES_DB=restored_fixture test-db sh /docker-entrypoint-initdb.d/10-roles.sh
dc run --rm --no-deps -e DB_HOST=test-db -e DB_NAME=restored_fixture migrate
restore_digest=$(dc run -T --rm --no-deps -e DB_HOST=test-db -e DB_NAME=restored_fixture web python - < ops/check-database.py)
test "$restore_digest" = "$saved"
dc run --rm --no-deps -e DB_HOST=test-db -e DB_NAME=restored_fixture web python manage.py fence_restored_database
restore_digest=$(dc run -T --rm --no-deps -e DB_HOST=test-db -e DB_NAME=restored_fixture web python - < ops/check-database.py)
test "$restore_digest" = "$saved"
echo "Verified $image_id on linux/$EXPECTED_ARCH including replacement and clean database restore."
